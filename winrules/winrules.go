// Package winrules generates the Hyprland window rules file for a game's timer window.
package winrules

import (
	"fmt"
	"math"
)

const (
	// LineHeight is the height in pixels given to each line of timer output.
	LineHeight   = 20
	DisplayWidth = 106
)

// Generate returns the contents of windowrules.lua for a game.
//
// The timer window must have the class "TIMER_<gameName>". The timer is only
// visible while the window described by matchField ("class" or "title") equal
// to matchValue is focused. height is the timer window height in pixels.
func Generate(gameName, matchField, matchValue string, height int) string {
	if matchField != "class" && matchField != "title" {
		panic(fmt.Sprintf("winrules: matchField must be \"class\" or \"title\", got %q", matchField))
	}
	return fmt.Sprintf(`-- Generated by the speedrun timer for %[1]s. Edits are overwritten on every run.
-- Start the timer terminal with class "TIMER_%[1]s".
hl.window_rule({
	match = {
		class = "^TIMER_%[1]s$",
	},
	pin = true,
	float = true,
	no_focus = true,
	no_initial_focus = true,
	size = { "%[2]d", "%[3]d" },
	move = { "0", "0" },
	border_size = 0,
})
local timer_visible = hl.window_rule({
	name = "timer-visible-%[1]s",
	match = {
		class = "^TIMER_%[1]s$",
	},
	opacity = "1 override 1 override 1 override",
})

local timer_hidden = hl.window_rule({
	name = "timer-hidden-%[1]s",
	match = {
		class = "^TIMER_%[1]s$",
	},
	opacity = "0 override 0 override 0 override",
})

-- Start hidden.
timer_visible:set_enabled(false)
timer_hidden:set_enabled(true)

hl.on("window.active", function(w)
	if w and w.%[4]s == %[5]q then
		timer_hidden:set_enabled(false)
		timer_visible:set_enabled(true)
	else
		timer_visible:set_enabled(false)
		timer_hidden:set_enabled(true)
	end
end)
`, gameName, uint32(math.Round(DisplayWidth*9.0384615384)), height, matchField, matchValue)
}
